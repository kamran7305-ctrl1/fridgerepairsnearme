#!/usr/bin/env python3
"""PreToolUse hook: block edits to files that must not be changed by hand."""
import json
import sys

PROTECTED = (
    "public/api/config.php",
    "package-lock.json",
    ".env",
)

try:
    data = json.load(sys.stdin)
    path = (data.get("tool_input") or {}).get("file_path", "")
except Exception:
    sys.exit(0)

normalized = path.replace("\\", "/")
for item in PROTECTED:
    if normalized == item or normalized.endswith("/" + item) or normalized.split("/")[-1] == item:
        print(
            f"Blocked: {item} is protected. config.php lives on the server and package-lock.json "
            "is generated by npm. Ask the user before changing it.",
            file=sys.stderr,
        )
        sys.exit(2)
sys.exit(0)
